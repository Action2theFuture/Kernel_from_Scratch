#!/bin/sh
# Generate a C table of kernel functions (address -> name) from a linked kernel.
# usage: gen_symbols.sh <nm> <kernel.elf>   (C source on stdout)
NM="$1"
ELF="$2"

echo '/* Generated by scripts/gen_symbols.sh - do not edit. */'
echo '#include "symbols.h"'
echo ''
echo 'const struct kernel_symbol g_kernel_symbols[] = {'
"$NM" -n "$ELF" | awk '$2 == "T" || $2 == "t" { printf "    { 0x%s, \"%s\" },\n", $1, $3; n++ }
                       END { if (n == 0) print "    { 0, \"\" }," }'
echo '};'
echo 'const size_t g_kernel_symbol_count ='
echo '    sizeof(g_kernel_symbols) / sizeof(g_kernel_symbols[0]);'
